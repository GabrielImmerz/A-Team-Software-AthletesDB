"""PostgreSQL backend for Streamlit Community Cloud.

Exposes the same public CRUD interface as database.py's SQLite backend.
Requires DATABASE_URL and psycopg2-binary. No migrations are performed:
new databases are initialized with an empty schema.
"""
from __future__ import annotations

from contextlib import contextmanager
from datetime import datetime
from io import BytesIO
import json
import os
from zipfile import ZipFile, ZIP_DEFLATED

from psycopg2 import connect as pg_connect
from psycopg2.extras import RealDictCursor

from domain import ATTEMPTS, gender_code, normalized_name, parse_date, safe_name, text, validate_result

_DATABASE_URL = os.environ.get('DATABASE_URL', '').strip()
if not _DATABASE_URL:
    raise RuntimeError('DATABASE_URL fehlt. Bitte in den Streamlit Secrets hinterlegen.')

# Keep dates as ISO text, as expected by the Streamlit UI and csv_import.py.
SCHEMA = '''
CREATE TABLE IF NOT EXISTS athletes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name TEXT NOT NULL,
  last_name TEXT NOT NULL,
  gender TEXT NOT NULL DEFAULT '-',
  birth_year INTEGER,
  notes TEXT NOT NULL DEFAULT '',
  active INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS competitions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  event_date TEXT NOT NULL,
  location TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- SQLite used a NOCASE uniqueness constraint. A functional unique index
-- provides the equivalent matching used by the code in PostgreSQL.
CREATE UNIQUE INDEX IF NOT EXISTS idx_competitions_unique_name_date_place
  ON competitions (lower(name), event_date, lower(location));
CREATE TABLE IF NOT EXISTS results (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  athlete_id INTEGER NOT NULL REFERENCES athletes(id) ON DELETE CASCADE,
  competition_id INTEGER NOT NULL REFERENCES competitions(id) ON DELETE CASCADE,
  bodyweight_kg DOUBLE PRECISION,
  weight_class TEXT NOT NULL DEFAULT '',
  s1 DOUBLE PRECISION, s2 DOUBLE PRECISION, s3 DOUBLE PRECISION,
  c1 DOUBLE PRECISION, c2 DOUBLE PRECISION, c3 DOUBLE PRECISION,
  snatch_best DOUBLE PRECISION,
  clean_jerk_best DOUBLE PRECISION,
  total_kg DOUBLE PRECISION,
  "placing" INTEGER,
  notes TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(athlete_id, competition_id)
);
CREATE INDEX IF NOT EXISTS idx_results_athlete ON results(athlete_id);
CREATE INDEX IF NOT EXISTS idx_results_competition ON results(competition_id);
CREATE INDEX IF NOT EXISTS idx_competitions_date ON competitions(event_date);
'''


@contextmanager
def connect(db_path=None):
    if db_path is not None:
        raise ValueError('db_path wird nur für die lokale SQLite-Version unterstützt.')
    # Establish a short-lived connection per request. This is suitable for
    # small club workloads and avoids stale connections after Neon suspends.
    conn = pg_connect(_DATABASE_URL, connect_timeout=15)
    try:
        with conn.cursor(cursor_factory=RealDictCursor) as cursor:
            yield cursor
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def init_db(db_path=None):
    with connect(db_path) as c:
        c.execute(SCHEMA)


def list_athletes(db_path=None):
    with connect(db_path) as c:
        c.execute('''SELECT * FROM athletes
            ORDER BY lower(last_name), lower(first_name), id''')
        return [dict(r) for r in c.fetchall()]


def load_all(db_path=None):
    """Return all UI lists with one read-only connection instead of three."""
    with connect(db_path) as c:
        c.execute('''SELECT * FROM athletes
            ORDER BY lower(last_name), lower(first_name), id''')
        athletes = [dict(r) for r in c.fetchall()]

        c.execute('''SELECT c.*, COUNT(r.id) AS starts
            FROM competitions c LEFT JOIN results r ON r.competition_id=c.id
            GROUP BY c.id ORDER BY c.event_date DESC,c.name''')
        competitions = [dict(r) for r in c.fetchall()]

        c.execute('''SELECT r.*,a.first_name,a.last_name,a.gender,
            c.name AS competition_name,c.event_date,c.location
            FROM results r JOIN athletes a ON a.id=r.athlete_id
            JOIN competitions c ON c.id=r.competition_id
            ORDER BY c.event_date,c.name,a.last_name,a.first_name,r.id''')
        results = [dict(r) for r in c.fetchall()]
    return athletes, competitions, results


def validate_year(value):
    if value is None or text(value) == '':
        return None
    year = int(value)
    if year < 1900 or year > datetime.today().year:
        raise ValueError('Geburtsjahr liegt außerhalb des gültigen Bereichs.')
    return year


def add_athlete(first_name, last_name, gender='-', birth_year=None, notes='', active=True, db_path=None):
    first, last = safe_name(first_name, 'Vorname'), safe_name(last_name, 'Nachname')
    year = validate_year(birth_year)
    with connect(db_path) as c:
        c.execute('''INSERT INTO athletes(first_name,last_name,gender,birth_year,notes,active)
                VALUES(%s,%s,%s,%s,%s,%s) RETURNING id''',
                  (first, last, gender_code(gender), year, text(notes)[:2000], int(active)))
        return c.fetchone()['id']


def edit_athlete(athlete_id, first_name, last_name, gender='-', birth_year=None, notes='', active=True, db_path=None):
    first, last = safe_name(first_name, 'Vorname'), safe_name(last_name, 'Nachname')
    with connect(db_path) as c:
        c.execute('''UPDATE athletes SET first_name=%s,last_name=%s,gender=%s,birth_year=%s,
                     notes=%s,active=%s WHERE id=%s''',
                  (first, last, gender_code(gender), validate_year(birth_year), text(notes)[:2000], int(active), athlete_id))
        if c.rowcount == 0:
            raise ValueError('Athlet wurde nicht gefunden.')


def delete_athlete(athlete_id, db_path=None):
    with connect(db_path) as c:
        c.execute('DELETE FROM athletes WHERE id=%s', (athlete_id,))
        if c.rowcount == 0:
            raise ValueError('Athlet wurde nicht gefunden.')


def _get_or_create_competition(c, name, date, location):
    c.execute('''INSERT INTO competitions(name,event_date,location) VALUES(%s,%s,%s)
                 ON CONFLICT DO NOTHING''', (name, date, location))
    c.execute('''SELECT id FROM competitions
                 WHERE lower(name)=lower(%s) AND event_date=%s AND lower(location)=lower(%s)''',
              (name, date, location))
    row = c.fetchone()
    if not row:
        raise RuntimeError('Wettkampf konnte nicht angelegt oder gefunden werden.')
    return row['id']


def create_competition(name, event_date, location='', db_path=None):
    name = safe_name(name, 'Wettkampf')
    date = parse_date(event_date)
    loc = text(location)[:200]
    with connect(db_path) as c:
        return _get_or_create_competition(c, name, date, loc)


